#!/usr/bin/env node
// @ts-check
// The tool catalog in docs/MCP.md, generated from src/ops.js (through the MCP server's own tool list),
// so the guide never drifts from the tools. Writes the part between the two markers.
//   node scripts/mcp-catalog.js           rewrite docs/MCP.md
//   node scripts/mcp-catalog.js --check   exit 1 when the committed catalog is stale
// test/i/mcp-docs.test.js fails when it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toolList, PROMPTS } from '../src/server/mcp.js';
import { MCP_OPS } from '../src/server/mcp.js';

export const GUIDE = fileURLToPath(new URL('../docs/MCP.md', import.meta.url));
export const START = '<!-- tool-catalog:start (generated by scripts/mcp-catalog.js from src/ops.js; do not edit by hand) -->';
export const END = '<!-- tool-catalog:end -->';

/** @param {string} s */
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** @param {any} s a JSON Schema @returns {string} */
function typeOf(s) {
  if (!s) return 'any';
  if (s.enum) return s.enum.map((/** @type {any} */ v) => JSON.stringify(v)).join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (Array.isArray(s.type)) return s.type.join(' or ');
  return s.type ?? 'any';
}

/** The catalog markdown. */
export function catalog() {
  const out = [START, ''];
  const tools = toolList();
  const free = tools.filter((t) => !MCP_OPS.find((o) => o.mcp?.name === t.name)?.callsModel).map((t) => `\`${t.name}\``);
  const paid = tools.filter((t) => MCP_OPS.find((o) => o.mcp?.name === t.name)?.callsModel).map((t) => `\`${t.name}\``);
  out.push(`${tools.length} tools. Free (no model call): ${free.join(', ')}. Call the model (cost API credits): ${paid.join(', ')}.`, '');
  for (const t of tools) {
    const op = /** @type {import('../src/ops.js').Op} */ (MCP_OPS.find((o) => o.mcp?.name === t.name));
    const a = /** @type {any} */ (t).annotations ?? {};
    out.push(`### \`${t.name}\`: ${t.title ?? t.name}`, '');
    out.push(t.description, '');
    const flags = [
      op.callsModel ? '**calls the model**' : 'free',
      a.readOnlyHint ? 'read-only' : 'writes to the map',
      ...(a.destructiveHint ? ['destructive (the old id stops working)'] : []),
      ...(a.idempotentHint ? ['idempotent'] : []),
      `token scope: \`${op.scope}\``,
      `HTTP: \`${op.http.method} ${op.http.path}\``,
    ];
    out.push(flags.join(' · '), '');
    const props = Object.entries(t.inputSchema.properties ?? {});
    if (props.length) {
      out.push('| Input | Type | Required | Description |', '|---|---|---|---|');
      for (const [name, s] of props) {
        out.push(`| \`${name}\` | ${cell(typeOf(s))} | ${(t.inputSchema.required ?? []).includes(name) ? 'yes' : 'no'} | ${cell(/** @type {any} */ (s).description ?? '')} |`);
      }
      out.push('');
    } else out.push('No inputs.', '');
  }
  out.push('### Prompts', '', 'Starting points a client can offer (MCP prompts):', '');
  out.push('| Prompt | What it does | Arguments |', '|---|---|---|');
  for (const p of PROMPTS) {
    out.push(`| \`${p.name}\` | ${cell(p.description)} | ${cell(p.arguments.map((x) => `\`${x.name}\`${x.required ? '' : ' (optional)'}`).join(', '))} |`);
  }
  out.push('', END);
  return out.join('\n');
}

/** The guide with its catalog replaced. @param {string} text */
export function withCatalog(text) {
  const i = text.indexOf(START.slice(0, 24));
  const j = text.indexOf(END);
  if (i < 0 || j < 0 || j < i) throw new Error(`docs/MCP.md has no catalog markers (${START.slice(0, 24)}… ${END})`);
  return `${text.slice(0, i)}${catalog()}${text.slice(j + END.length)}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = readFileSync(GUIDE, 'utf8');
  const next = withCatalog(text);
  if (process.argv.includes('--check')) {
    if (next !== text) { console.error('docs/MCP.md: the tool catalog is stale: run node scripts/mcp-catalog.js'); process.exit(1); }
    console.error('docs/MCP.md: the tool catalog is up to date');
  } else {
    writeFileSync(GUIDE, next);
    console.error('wrote the tool catalog in docs/MCP.md');
  }
}
